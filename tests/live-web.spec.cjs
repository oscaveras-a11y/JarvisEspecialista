const {test,expect}=require('@playwright/test');
const crypto=require('node:crypto');
test('the approved panel sends a file to CORE and downloads its real report',async({page})=>{
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto('/');
 await expect(page.locator('body')).toHaveAttribute('data-engine','connected');
 await expect(page.locator('#stat-total')).toHaveText('0');
 await expect(page.locator('#demo-notice')).toContainText('Motor conectado');
 await page.getByRole('button',{name:'Nova investigação',exact:true}).first().click();
 for(const[id,value]of Object.entries({'f-project':'Teste real pelo painel','f-objective':'Conferir hash conhecido','f-owner':'Proprietário','f-authorization':'Arquivo sintético autorizado'}))await page.locator('#'+id).fill(value);
 await page.getByRole('button',{name:'Criar investigação'}).click();
 await expect(page.locator('#investigations-table')).toContainText('Teste real pelo painel');
 await page.getByRole('button',{name:'Tarefas e progresso',exact:true}).click();
 const bytes=Buffer.from('%PDF-1.7\nSynthetic file sent through the actual panel\n');
 const hash=crypto.createHash('sha256').update(bytes).digest('hex');
 await page.locator('#task-file').setInputFiles({name:'sample.pdf',mimeType:'application/pdf',buffer:bytes});
 await page.locator('#form-new-task button[type=submit]').click();
 await expect(page.locator('#engine-results')).toContainText(hash,{timeout:30000});
 await expect(page.locator('#tasks-list')).toContainText('concluída');
 await page.screenshot({path:'test-results/connected-results.png',fullPage:true});
 await page.reload();
 await expect(page.locator('body')).toHaveAttribute('data-engine','connected');
 await expect(page.locator('#stat-total')).toHaveText('1');
 await page.getByRole('navigation',{name:'Navegação principal'}).getByRole('button',{name:'Relatórios',exact:true}).click();
 const download=page.waitForEvent('download');await page.getByRole('button',{name:'Gerar e baixar relatório'}).click();
 const chunks=[];for await(const chunk of await(await download).createReadStream())chunks.push(chunk);
 expect(Buffer.concat(chunks).toString('utf8')).toContain(hash);
 await page.getByRole('navigation',{name:'Navegação principal'}).getByRole('button',{name:'Investigações',exact:true}).click();
 const row=page.locator('#investigations-table tr').filter({hasText:'Teste real pelo painel'});
 await row.getByRole('button',{name:'pausar',exact:true}).click();await expect(row).toContainText('pausado');
 await row.getByRole('button',{name:'retomar',exact:true}).click();
 page.on('dialog',dialog=>dialog.type()==='prompt'?dialog.accept('Teste encerrado'):dialog.accept());
 await row.getByRole('button',{name:'cancelar',exact:true}).click();await expect(row).toContainText('cancelado');
 expect(errors).toEqual([]);
});
